def normalize_language(value: str | None) -> str:
    return "ru" if str(value or "").strip().lower() in {"ru", "russian", "рус", "русский"} else "en"


def set_language(value: str) -> str:
    global _language
    _language = normalize_language(value)
    return _language


def language() -> str:
    return _language


def t(key: str, **kwargs: object) -> str:
    bundle = STRINGS.get(_language) or STRINGS["en"]
    text = bundle.get(key) or STRINGS["en"].get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text
